import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';

const root = process.cwd();
const manifestPath = resolve(root, 'dist/.vite/manifest.json');
const outputPath = resolve(root, 'dist/sw.js');
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));

const assets = new Set(['./', './index.html', './manifest.webmanifest', './assets/icon.png', './assets/icon-192.png']);
for (const entry of Object.values(manifest)) {
  if (entry.file) assets.add(`./${entry.file}`);
  for (const cssFile of entry.css ?? []) assets.add(`./${cssFile}`);
  for (const assetFile of entry.assets ?? []) assets.add(`./${assetFile}`);
}

const cacheSuffix = createHash('sha256').update(JSON.stringify([...assets].sort())).digest('hex').slice(0, 10);
const worker = `/* Generated by scripts/generate-sw.mjs. */
const CACHE_NAME = 'timedeck-static-v2-${cacheSuffix}';
const PRECACHE_URLS = ${JSON.stringify([...assets])};
self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    await cache.addAll(PRECACHE_URLS.map((path) => new URL(path, self.registration.scope).href));
    await self.skipWaiting();
  })());
});
self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((key) => key.startsWith('timedeck-') && key !== CACHE_NAME).map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        const cache = await caches.open(CACHE_NAME);
        await cache.put(new URL('./index.html', self.registration.scope).href, response.clone());
        return response;
      } catch {
        return (await caches.match(new URL('./index.html', self.registration.scope).href)) || Response.error();
      }
    })());
    return;
  }
  event.respondWith((async () => {
    const cached = await caches.match(request);
    if (cached) return cached;
    try {
      const response = await fetch(request);
      if (response.ok) {
        const cache = await caches.open(CACHE_NAME);
        await cache.put(request, response.clone());
      }
      return response;
    } catch {
      return Response.error();
    }
  })());
});
`;
await writeFile(outputPath, worker, 'utf8');
console.log(`Generated service worker with ${assets.size} precached resources.`);
